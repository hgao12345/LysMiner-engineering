#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
Process and export LYS-MUT prediction results.

The script reads the pickle file generated by the LYS-MUT
prediction step, filters generated variants according to their
masked-position prediction scores, and exports the selected
sequences as CSV and JSON files.

Example
-------
python step_5_get_result.py \
    --data_name example_seq \
    --prediction_dir ./example/example_seq/train_data/prediction
"""

import argparse
import json
import pickle
from pathlib import Path

import pandas as pd
from tqdm import tqdm


# ============================================================
# 1. Parse arguments
# ============================================================

def parse_args():
    parser = argparse.ArgumentParser(
        description=(
            "Process and export LYS-MUT prediction results."
        )
    )

    parser.add_argument(
        "--data_name",
        type=str,
        required=True,
        help=(
            "Name of the prediction dataset. "
            "File extensions such as .fasta, .pkl, .csv, "
            "or .json are optional."
        ),
    )

    parser.add_argument(
        "--prediction_dir",
        type=Path,
        required=True,
        help=(
            "Directory containing the prediction pickle file "
            "generated by step_4_run_predict.py."
        ),
    )

    return parser.parse_args()


# ============================================================
# 2. Clean dataset name
# ============================================================

def clean_data_name(data_name):
    """Remove known file extensions from the dataset name."""

    suffixes = [
        ".fasta",
        ".pkl",
        ".csv",
        ".json",
    ]

    for suffix in suffixes:
        if data_name.endswith(suffix):
            data_name = data_name[:-len(suffix)]

    return data_name


# ============================================================
# 3. Load prediction results
# ============================================================

def load_predictions(pickle_file):
    """Load prediction results from a pickle file."""

    if not pickle_file.exists():
        raise FileNotFoundError(
            "Prediction pickle file not found:\n"
            f"{pickle_file}"
        )

    with open(pickle_file, "rb") as f:
        pickle_res = pickle.load(f)

    if len(pickle_res) == 0:
        raise ValueError(
            "The prediction pickle file contains no records."
        )

    return pickle_res


# ============================================================
# 4. Process prediction results
# ============================================================

def process_predictions(pickle_res):
    """
    Select generated sequences according to masked-position scores.

    The wild-type sequence is added with label = 0.
    Generated candidate variants are assigned label = -1.
    """

    select_df = []
    select_json = []

    # --------------------------------------------------------
    # Add wild-type sequence
    # --------------------------------------------------------

    wt_id = (
        pickle_res[0]["seq_id"]
        .split("_")[0]
        + "_WT"
    )

    wt_seq = "".join(
        pickle_res[0]["seq"]
    )

    select_df.append(
        {
            "id": wt_id,
            "seq": wt_seq,
            "mask_logits_mean": 0,
            "mask_logits_min": 0,
            "label": 0,
        }
    )

    select_json.append(
        {
            "id": wt_id,
            "original_seq": wt_seq,
            "pred_seq": wt_seq,
            "truncate_token": pickle_res[0]["seq"],
            "mask_lm_positions": [],
            "logits": [],
        }
    )

    # --------------------------------------------------------
    # Select generated sequences
    # --------------------------------------------------------

    for pred_info in tqdm(
        pickle_res,
        desc="Processing predictions",
    ):

        # Maximum prediction score at each mutated position.
        position_logits = (
            pred_info["logits"]
            .max(axis=1)
        )

        # Minimum score among all mutated positions.
        logits_min = (
            position_logits.min()
        )

        # Keep sequences for which all selected positions
        # have a positive prediction score.
        if logits_min > 0:

            pred_seq = "".join(
                pred_info["pred_seq"]
            )

            original_seq = "".join(
                pred_info["seq"]
            )

            select_df.append(
                {
                    "id": pred_info["seq_id"],
                    "seq": pred_seq,
                    "mask_logits_mean":
                        position_logits.mean(),
                    "mask_logits_min":
                        position_logits.min(),
                    "label": -1,
                }
            )

            select_json.append(
                {
                    "id": pred_info["seq_id"],
                    "original_seq": original_seq,
                    "pred_seq": pred_seq,
                    "truncate_token":
                        pred_info["truncate_token"],
                    "mask_lm_positions":
                        pred_info["mask_lm_positions"],
                    "logits":
                        position_logits.tolist(),
                }
            )

    return select_df, select_json


# ============================================================
# 5. Save results
# ============================================================

def save_results(
    select_df,
    select_json,
    csv_file,
    json_file,
):
    """Save selected sequences as CSV and JSON files."""

    result_df = pd.DataFrame(
        select_df
    )

    result_df.to_csv(
        csv_file,
        index=False,
    )

    with open(
        json_file,
        "w",
        encoding="utf-8",
    ) as f:

        json.dump(
            select_json,
            f,
            indent=4,
        )


# ============================================================
# Main
# ============================================================

def main():
    args = parse_args()

    # --------------------------------------------------------
    # Resolve parameters
    # --------------------------------------------------------

    data_name = clean_data_name(
        args.data_name
    )

    prediction_dir = (
        args.prediction_dir
        .expanduser()
        .resolve()
    )

    if not prediction_dir.exists():
        raise FileNotFoundError(
            "Prediction directory not found:\n"
            f"{prediction_dir}"
        )

    # --------------------------------------------------------
    # Input / output files
    # --------------------------------------------------------

    pickle_file = (
        prediction_dir /
        f"{data_name}.pkl"
    )

    csv_file = (
        prediction_dir /
        f"{data_name}.csv"
    )

    json_file = (
        prediction_dir /
        f"{data_name}.json"
    )

    # --------------------------------------------------------
    # Display configuration
    # --------------------------------------------------------

    print("\n" + "=" * 70)
    print("Process LYS-MUT prediction results")
    print("=" * 70)

    print(
        f"Prediction directory : {prediction_dir}"
    )

    print(
        f"Input pickle         : {pickle_file}"
    )

    print(
        f"CSV output           : {csv_file}"
    )

    print(
        f"JSON output          : {json_file}"
    )

    # --------------------------------------------------------
    # Load predictions
    # --------------------------------------------------------

    pickle_res = load_predictions(
        pickle_file
    )

    print(
        f"Total prediction records: {len(pickle_res)}"
    )

    # --------------------------------------------------------
    # Process predictions
    # --------------------------------------------------------

    select_df, select_json = (
        process_predictions(
            pickle_res
        )
    )

    # --------------------------------------------------------
    # Save results
    # --------------------------------------------------------

    save_results(
        select_df=select_df,
        select_json=select_json,
        csv_file=csv_file,
        json_file=json_file,
    )

    # --------------------------------------------------------
    # Summary
    # --------------------------------------------------------

    print("\n" + "=" * 70)
    print("Completed")
    print("=" * 70)

    print(
        f"Selected sequences : {len(select_df)}"
    )

    print(
        f"CSV output         : {csv_file}"
    )

    print(
        f"JSON output        : {json_file}"
    )


if __name__ == "__main__":
    main()
